// @vitest-environment node
import { randomBytes } from "node:crypto";
import postgres from "postgres";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { getConfirmedAnswerKey } from "./answer-key";
import { evaluateReferenceEligibility, referenceKeyFingerprint } from "./answer-key-eligibility";
import { eligibleReferenceFeedbackSql, loadReferenceInputs, persistReferenceReceipt, readReferenceEligibility, referenceFeeFingerprint, type ReferenceInput } from "./answer-key-reference-store";
import { loadKnoxBatch, scoreKnoxBatch } from "@/lib/agents/knox/batch-review";
import { runKnoxMisses } from "@/lib/agents/deming/knox-misses";
import { refreshReferenceEligibility } from "@/lib/agents/answer-key-eligibility";
import { CONSUMER_TEXT, fixtureReference, referenceHash } from "./__fixtures__/answer-key-reference";
import { loadCategoryModel, resetCategoryModelCache } from "@/lib/agents/darwin/category-model";
import { JSON_TEXT_PASSTHROUGH, NUMERIC_AS_NUMBER, TEXT_WITHOUT_NUL } from "./connection";

const connection = process.env.E2E_DATABASE_URL;
const schema = `reference_eligibility_${randomBytes(8).toString("hex")}`;

describe.skipIf(!connection)("reference eligibility in isolated PostgreSQL", () => {
  let admin: postgres.Sql, db: postgres.Sql<{ numeric: number; json: unknown; text: string }>;
  beforeAll(async () => {
    if (!connection || !["127.0.0.1", "localhost", "[::1]"].includes(new URL(connection).hostname)) throw new Error("Eligibility SQL tests require a loopback fixture");
    admin = postgres(connection, { ssl: "require", prepare: false, onnotice: () => undefined });
    const [schemaState]=await admin`SELECT to_regclass('public.pipeline_feedback') IS NOT NULL AS ready`;
    if(!schemaState.ready) throw new Error("Initialize the owned loopback database with tests/e2e/production-schema.sql before running reference eligibility SQL tests (unchanged feedback readiness checks public metadata)");
    await admin`CREATE SCHEMA ${admin(schema)}`;
    db = postgres(connection, { ssl: "require", prepare: false, onnotice: () => undefined, connection: { search_path: schema },
      types: { numeric: NUMERIC_AS_NUMBER, json: JSON_TEXT_PASSTHROUGH, text: TEXT_WITHOUT_NUL } });
    // Only the currently used schema fields, no production tables/defaults/sequences/data.
    await db.unsafe(`
      CREATE TABLE institution_sources (id bigint PRIMARY KEY, institution_name text, website_url text, fee_schedule_url text);
      CREATE TABLE answer_key_institutions (id bigint PRIMARY KEY, institution_id bigint, document_url text, document_type text,
        content_hash text, status text, confirmed_by text, confirmed_at timestamptz, notes text, updated_at timestamptz DEFAULT now());
      CREATE TABLE answer_key_fees (id bigint PRIMARY KEY, answer_key_institution_id bigint, canonical_key text, amount numeric,
        amount_kind text, frequency text, conditions text, source_line text, uncertain boolean, status text,
        confirmed_by text, confirmed_at timestamptz, updated_at timestamptz DEFAULT now());
      CREATE TABLE source_documents (id bigint PRIMARY KEY, institution_id bigint, document_url text, content_hash text,
        status text, superseded_by_id bigint, duplicate_of_id bigint);
      CREATE TABLE agent_source_texts (id bigint PRIMARY KEY, institution_id bigint, source_document_id bigint, text_hash text,
        status text, document_kind text, normalized_text text, updated_at timestamptz DEFAULT now());
      CREATE TABLE agent_run_steps (id bigint PRIMARY KEY, agent_run_id integer, step_key text);
      CREATE TABLE agent_run_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, agent_run_id integer NOT NULL,
        step_id bigint, event_type text NOT NULL, status text, message text, detail jsonb NOT NULL, created_at timestamptz DEFAULT now());
      CREATE INDEX reference_event_type_time ON agent_run_events (event_type, created_at DESC);
      CREATE TABLE pipeline_feedback (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, about_stage text, check_name text,
        kind text, signal text, weight numeric, institution_id bigint, canonical_fee_key text, amount numeric, source_url text,
        evidence jsonb, dedupe_key text UNIQUE);
      CREATE TABLE raw_fee_observations (fee_raw_id bigint PRIMARY KEY,institution_id bigint,source_document_id bigint,source_url text,
        fee_name text,amount numeric,outlier_flags jsonb,source text,created_at timestamptz);
      CREATE TABLE verified_fee_observations (fee_verified_id bigint,fee_raw_id bigint,review_status text,canonical_fee_key text,validation_flags jsonb,amount numeric);
      CREATE TABLE published_fee_records (fee_published_id bigint,lineage_ref bigint,rolled_back_at timestamptz,rolled_back_reason text);
      CREATE TABLE eval_cases (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,case_key text UNIQUE,dataset text,status text,agent text,
        check_name text,error_class text,severity text,institution_id bigint,source_document_id bigint,source_url text,source_text_hash text,
        input jsonb,expected jsonb,label_provenance text,agent_run_id bigint,last_checked_at timestamptz,last_caught boolean,last_verdict text,
        last_run_id bigint,updated_at timestamptz DEFAULT now());
      CREATE TABLE published_fee_catalog (fee_name text, canonical_fee_key text);
    `);
  });
  beforeEach(async () => {
    resetCategoryModelCache();
    await db.unsafe("TRUNCATE institution_sources, answer_key_institutions, answer_key_fees, source_documents, agent_source_texts, agent_run_steps, agent_run_events, pipeline_feedback, published_fee_catalog, eval_cases, raw_fee_observations, verified_fee_observations, published_fee_records RESTART IDENTITY");
    await db`INSERT INTO institution_sources VALUES (999, 'Fixture Bank', 'https://bank.example/', 'https://bank.example/consumer-fees.pdf')`;
    await db`INSERT INTO answer_key_institutions (id,institution_id,document_url,document_type,content_hash,status,confirmed_by,confirmed_at)
      VALUES (1,999,'https://bank.example/consumer-fees.pdf','text_pdf',${referenceHash(CONSUMER_TEXT)},'confirmed','existing person','2026-10-18T00:00:00Z')`;
    await db`INSERT INTO answer_key_fees (id,answer_key_institution_id,canonical_key,amount,amount_kind,frequency,source_line,uncertain,status,confirmed_by,confirmed_at)
      VALUES (1,1,'overdraft',25,'fixed','per_item','Overdraft fee $25',false,'confirmed','existing person','2026-10-18T00:00:00Z')`;
    await db`INSERT INTO source_documents VALUES (10,999,'https://bank.example/consumer-fees.pdf',${referenceHash(CONSUMER_TEXT)},'success',NULL,NULL)`;
    await db`INSERT INTO agent_source_texts (id,institution_id,source_document_id,text_hash,status,document_kind,normalized_text)
      VALUES (11,999,10,${referenceHash(CONSUMER_TEXT)},'completed','fee_schedule',${CONSUMER_TEXT})`;
    await db`INSERT INTO agent_run_steps VALUES (2,10,'score-answer-key')`;
    await db`INSERT INTO published_fee_catalog VALUES ('Stop Payment Fee','stop_payment')`;
  });
  afterAll(async () => {
    resetCategoryModelCache();
    if (db) await db.end();
    if (admin) { await admin`DROP SCHEMA IF EXISTS ${admin(schema)} CASCADE`; await admin.end(); }
  });
  const asDb = (value: unknown = db) => value as NonNullable<Parameters<typeof loadReferenceInputs>[0]>;
  async function observed(input: ReferenceInput) {
    const fixture = fixtureReference(CONSUMER_TEXT);
    return evaluateReferenceEligibility({ key: input.key, sources: input.sources, pages: [fixture.page],
      asOf: new Date().toISOString(), discovery: { entryUrls: ["https://bank.example/"], examinedUrls: [input.key.documentUrl],
        candidateUrls: [input.key.documentUrl], completeWithinProtocol: true, linkedFromOfficialSite: true, limitReason: null } });
  }
  async function approve() {
    const [input] = await loadReferenceInputs(asDb());
    const receipt = await observed(input);
    expect(receipt.status).toBe("eligible");
    const id = await persistReferenceReceipt(asDb(), input, receipt, 10, 2);
    expect(id).toBeGreaterThan(0);
    return { input, receipt, id: id! };
  }
  async function addFeedback() {
    const { input, receipt, id } = await approve();
    const evidence = { source_line: "Overdraft fee $25", amount_kind: "fixed", answer_key_fee_id: 1,
      reference_protocol: 1, reference_event_id: id, reference_key_fingerprint: referenceKeyFingerprint(input.key),
      reference_fee_fingerprint: referenceFeeFingerprint(input.key, 1) };
    await db`INSERT INTO pipeline_feedback (about_stage,check_name,kind,signal,weight,institution_id,canonical_fee_key,amount,source_url,evidence,dedupe_key)
      VALUES ('extract','answer_key','answer_key','right',1,999,'overdraft',25,${input.key.documentUrl},${JSON.stringify(evidence)}::jsonb,'fixture-origin')`;
    return { input, receipt, id, evidence };
  }
  async function trustedFeedbackCount() {
    const snapshot = await readReferenceEligibility(asDb());
    const rows = await db`SELECT f.id FROM pipeline_feedback f WHERE ${eligibleReferenceFeedbackSql(asDb(), "f", snapshot)}`;
    return rows.length;
  }

  it("does not erase explicit key-byte supersession by issuing another fresh receipt", async () => {
    await approve();await db`UPDATE source_documents SET superseded_by_id=20 WHERE id=10`;
    const [input]=await loadReferenceInputs(asDb()),receipt=await observed(input);
    expect(receipt).toMatchObject({status:"unknown",facts:{current:{reasons:["reference_source_superseded"]}}});
    expect(await persistReferenceReceipt(asDb(),input,receipt,10,2)).toBeGreaterThan(0);
    expect((await readReferenceEligibility(asDb())).cohort.state).toBe("no_measurement");
  });

  it("binds Knox batch teaching to exact source bytes, retaining a same-bytes mirror and frozen expected prices", async () => {
    await db`INSERT INTO source_documents VALUES
      (20,999,'https://bank.example/consumer-fees.pdf',${referenceHash("old edition")},'success',NULL,NULL),
      (30,999,'https://bank.example/mirror.pdf',${referenceHash(CONSUMER_TEXT)},'success',NULL,NULL),
      (40,999,'https://bank.example/consumer-fees.pdf',NULL,'success',NULL,NULL)`;
    await approve();const snapshot=await readReferenceEligibility(asDb());
    for(const [id,documentId,url] of [[1,10,"https://bank.example/consumer-fees.pdf"],[2,20,"https://bank.example/consumer-fees.pdf"],
      [3,30,"https://bank.example/mirror.pdf"],[4,40,"https://bank.example/consumer-fees.pdf"],[5,null,"https://bank.example/consumer-fees.pdf"]] as const) {
      await db`INSERT INTO raw_fee_observations VALUES (${id},999,${documentId},${url},'Overdraft fee',123,'[]'::jsonb,'knox',now()-interval '2 days')`;
      await db`INSERT INTO verified_fee_observations VALUES (${id},${id},'approved','overdraft','[]'::jsonb,123)`;
      await db`INSERT INTO published_fee_records VALUES (${id},${id},NULL,NULL)`;
    }
    // A concurrent key edit must not replace the operation's frozen expected price of25.
    await db`UPDATE answer_key_fees SET amount=123`;
    const rows=await loadKnoxBatch(asDb(),0,500,snapshot);
    expect(rows.map(row=>[Number(row.fee_raw_id),row.answer_key_bank,row.answer_key_match])).toEqual([
      [1,true,false],[2,false,false],[3,true,false],[4,false,false],[5,false,false]]);
    expect(scoreKnoxBatch(rows).score).toMatchObject({answerKeyChecked:2,answerKeyMismatched:2});
  });

  it("runs the injected current-source producer through durable eligibility and gated score input", async () => {
    const fetchImpl = (async (url: string | URL | Request) => new Response(String(url).endsWith("/consumer-fees.pdf")
      ? CONSUMER_TEXT : '<html><main><a href="/consumer-fees.pdf">Consumer Fee Schedule</a></main></html>',
      { headers: { "Content-Type": String(url).endsWith(".pdf") ? "text/plain" : "text/html" } })) as typeof fetch;
    const before = await readReferenceEligibility(asDb());
    expect(before.cohort.state).toBe("no_measurement");
    const result = await refreshReferenceEligibility({ db: asDb(),runId: 10,stepId: 2,dryRun: false,snapshot: before,fetchImpl });
    expect(result).toMatchObject({ attempted: 1,persisted: 1,failed: 0,snapshot: { cohort: { eligibleBanks: 1,eligibleFees: 1,state: "measured" } } });
    expect(await getConfirmedAnswerKey(asDb(),result.snapshot)).toHaveLength(1);
  });

  it("bounds stalled source work inside a real aged transaction and rotates unattempted keys first", async () => {
    for(let id=2;id<=5;id++) {
      await db`INSERT INTO institution_sources VALUES (${1000+id},'Fixture Bank',${`https://bank${id}.example/`},${`https://bank${id}.example/consumer-fees.pdf`})`;
      await db`INSERT INTO answer_key_institutions (id,institution_id,document_url,document_type,content_hash,status,confirmed_by)
        VALUES (${id},${1000+id},${`https://bank${id}.example/consumer-fees.pdf`},'text_pdf',${referenceHash(CONSUMER_TEXT)},'confirmed','fixture person')`;
      await db`INSERT INTO answer_key_fees (id,answer_key_institution_id,canonical_key,amount,amount_kind,source_line,uncertain,status)
        VALUES (${id},${id},'overdraft',25,'fixed','Overdraft fee $25',false,'confirmed')`;
    }
    await db.begin(async txRaw=>{
      const tx=asDb(txRaw);await tx`SELECT pg_sleep(1.1)`;
      const snapshot=await readReferenceEligibility(tx), started=Date.now();
      const first=await refreshReferenceEligibility({db:tx,runId:10,stepId:2,dryRun:false,snapshot,budgetMs:20,
        fetchImpl:(()=>new Promise(()=>undefined)) as typeof fetch});
      expect(Date.now()-started).toBeLessThan(1000);
      expect(first).toMatchObject({attempted:3,persisted:3,snapshot:{cohort:{state:"no_measurement",eligibleBanks:0}}});
    });
    const calls:string[]=[];
    const fetchImpl=(async(url:unknown)=>{calls.push(String(url));return new Response(CONSUMER_TEXT,{headers:{"Content-Type":"text/plain"}});}) as typeof fetch;
    await refreshReferenceEligibility({db:asDb(),runId:10,stepId:2,dryRun:false,snapshot:await readReferenceEligibility(asDb()),fetchImpl,budgetMs:2000});
    expect(calls.slice(0,2)).toEqual(["https://bank4.example/","https://bank5.example/"]);
  });

  it.each([
    ["iTHINK business document", "Business Fee Schedule\nOverdraft fee $25\nStop payment fee $20\nWire transfer fee $15\nBusiness Account Disclosures", "business_document"],
    ["Texas Capital legacy product", "Consumer Fee Schedule\nOverdraft fee $25\nStop payment fee $20\nWire transfer fee $15\nClosed to new accounts since 2023", "legacy_not_current"],
    ["TDECU rates hub", "Consumer Accounts\nSavings APY 4.25%\nMinimum balance $500", "not_priced_schedule"],
  ])("durably excludes the historical %s failure mode from score input", async (_, text, reason) => {
    await db`UPDATE answer_key_institutions SET content_hash=${referenceHash(text)}`;
    const [input] = await loadReferenceInputs(asDb());
    const page = fixtureReference(text).page;
    const receipt = evaluateReferenceEligibility({ ...input,pages:[page],asOf:new Date().toISOString(),
      discovery: { entryUrls:["https://bank.example/"],examinedUrls:[input.key.documentUrl],candidateUrls:[input.key.documentUrl],
        completeWithinProtocol:true,linkedFromOfficialSite:true,limitReason:null } });
    expect(receipt.status).toBe("rejected");
    expect(receipt.reasons).toContain(reason);
    expect(await persistReferenceReceipt(asDb(),input,receipt,10,2)).toBeGreaterThan(0);
    const snapshot=await readReferenceEligibility(asDb());
    expect(snapshot.cohort).toMatchObject({ state:"no_measurement",eligibleBanks:0,excludedBanks:1 });
    expect(await getConfirmedAnswerKey(asDb(),snapshot)).toEqual([]);
  });

  async function createBoundMissCase() {
    await approve();
    // The fresh reference contains the fee; an imperfect stored text misses it.
    await db`UPDATE agent_source_texts SET normalized_text='Consumer Fee Schedule\nStop payment fee $20\nWire transfer fee $15'`;
    const result=await runKnoxMisses({ db:asDb(),runId:10 });
    expect(result.newCases).toBe(1);
    const [row]=await db`SELECT * FROM eval_cases`;
    expect(row.input.reference_protocol).toBe(1);
    return row;
  }

  it("replays an originally bound case after renewal without changing its frozen evidence", async () => {
    const before=await createBoundMissCase();
    await approve();
    await db`UPDATE agent_source_texts SET normalized_text=${CONSUMER_TEXT}`;
    const result=await runKnoxMisses({ db:asDb(),runId:11 });
    expect(result).toMatchObject({ activated:1,newCases:0,referenceExcludedCases:0 });
    const [after]=await db`SELECT * FROM eval_cases`;
    expect(after.status).toBe("active");expect(after.input).toEqual(before.input);
  });

  it.each(["missing origin","forged origin","edited payload","ineligible key"])("excludes an old replay case with %s without relabelling it key_fee_removed", async (change) => {
    await createBoundMissCase();
    if(change==="missing origin") await db`UPDATE eval_cases SET input=input-'reference_event_id'`;
    if(change==="forged origin") await db`UPDATE eval_cases SET input=input||'{"reference_event_id":99999}'::jsonb`;
    if(change==="edited payload") await db`UPDATE eval_cases SET input=input||'{"amount":999}'::jsonb`;
    if(change==="ineligible key") await db`UPDATE answer_key_institutions SET document_url='https://bank.example/other.pdf'`;
    const result=await runKnoxMisses({ db:asDb(),runId:11 });
    expect(result).toMatchObject({ activated:0,regressions:[],retired:0,referenceExcludedCases:1 });
    expect((await db`SELECT last_verdict FROM eval_cases`)[0].last_verdict).toBe("missed");
  });

  it("records a durable decision, reuses one snapshot, and preserves human confirmation", async () => {
    const before = await db`SELECT confirmed_by,confirmed_at,status FROM answer_key_institutions`;
    await approve();
    const snapshot = await readReferenceEligibility(asDb());
    expect(snapshot.keys[0].status).toBe("eligible");
    expect(await getConfirmedAnswerKey(asDb(), snapshot)).toMatchObject([{ institutionId: 999, fees: [{ amount: 25 }] }]);
    expect(await db`SELECT confirmed_by,confirmed_at,status FROM answer_key_institutions`).toEqual(before);
  });

  it("uses wall-clock event time after an enclosing ledger transaction has already aged", async () => {
    await db.begin(async (txRaw) => {
      const tx = txRaw as unknown as typeof db;
      await tx`SELECT pg_sleep(1.1)`;
      const [input] = await loadReferenceInputs(asDb(tx as unknown as postgres.Sql));
      const id = await persistReferenceReceipt(asDb(tx as unknown as postgres.Sql), input, await observed(input), 10, 2);
      expect(id).toBeGreaterThan(0);
      const [clock] = await tx`SELECT extract(epoch FROM (created_at-current_timestamp))::float AS age FROM agent_run_events WHERE id=${id!}`;
      expect(clock.age).toBeGreaterThan(1);
      expect((await readReferenceEligibility(asDb(tx as unknown as postgres.Sql))).keys[0].status).toBe("eligible");
    });
  });

  it.each(["price", "category", "fee add", "document", "source add", "source bytes", "text hash"])("refuses a stale observation after %s changes before persistence", async (change) => {
    const [input] = await loadReferenceInputs(asDb());
    const receipt = await observed(input);
    if (change === "price") await db`UPDATE answer_key_fees SET amount=26`;
    if (change === "category") await db`UPDATE answer_key_fees SET canonical_key='nsf'`;
    if (change === "fee add") await db`INSERT INTO answer_key_fees SELECT 2,answer_key_institution_id,canonical_key,amount,amount_kind,frequency,conditions,source_line,uncertain,status,confirmed_by,confirmed_at,updated_at FROM answer_key_fees`;
    if (change === "document") await db`UPDATE answer_key_institutions SET document_url='https://bank.example/new-fees.pdf'`;
    if (change === "source add") await db`INSERT INTO source_documents VALUES (20,999,'https://bank.example/new.pdf','different','success',NULL,NULL)`;
    if (change === "source bytes") await db`UPDATE source_documents SET content_hash='different'`;
    if (change === "text hash") await db`UPDATE agent_source_texts SET text_hash='different'`;
    expect(await persistReferenceReceipt(asDb(), input, receipt, 10, 2)).toBeNull();
    expect((await readReferenceEligibility(asDb())).keys[0].status).toBe("unknown");
  });

  it("never authorizes a missing real ledger run/step or persistence failure", async () => {
    const [input] = await loadReferenceInputs(asDb());
    const receipt = await observed(input);
    expect(await persistReferenceReceipt(asDb(), input, receipt, 10, 999)).toBeNull();
    expect(await persistReferenceReceipt(asDb(), input, receipt, 0, 2)).toBeNull();
    await db`ALTER TABLE agent_run_events ADD CONSTRAINT synthetic_refusal CHECK (false)`;
    await expect(persistReferenceReceipt(asDb(), input, receipt, 10, 2)).rejects.toThrow();
    await db`ALTER TABLE agent_run_events DROP CONSTRAINT synthetic_refusal`;
    expect((await readReferenceEligibility(asDb())).keys[0].status).toBe("unknown");
  });

  it.each(["unknown", "malformed", "unbound step"])("retains a newest %s tombstone instead of reviving an older eligible event", async (kind) => {
    const { receipt } = await approve();
    const tombstone = kind === "unknown" ? { ...receipt, status: "unknown" } : kind === "unbound step" ? receipt : { answerKeyId: 1 };
    await db`INSERT INTO agent_run_events (agent_run_id,step_id,event_type,status,message,detail,created_at)
      VALUES (10,${kind === 'unbound step' ? null : 2},'answer_key.eligibility','info','fixture tombstone',${JSON.stringify(tombstone)}::jsonb,clock_timestamp())`;
    expect((await readReferenceEligibility(asDb())).keys[0].status).toBe("unknown");
  });

  it.each(["missing protocol", "missing origin", "forged origin", "wrong-key origin", "institution", "category", "amount", "source URL", "source line", "fee name", "weight"])("excludes historical/edited feedback with %s", async (change) => {
    const { receipt } = await addFeedback();
    expect(await trustedFeedbackCount()).toBe(1);
    if (change === "missing protocol") await db`UPDATE pipeline_feedback SET evidence=evidence-'reference_protocol'`;
    if (change === "missing origin") await db`UPDATE pipeline_feedback SET evidence=evidence-'reference_event_id'`;
    if (change === "forged origin") await db`UPDATE pipeline_feedback SET evidence=evidence||' {"reference_event_id":99999}'::jsonb`;
    if (change === "wrong-key origin") {
      const [event] = await db`INSERT INTO agent_run_events (agent_run_id,step_id,event_type,status,message,detail,created_at)
        VALUES (10,2,'answer_key.eligibility','info','wrong key',${JSON.stringify({ ...receipt, answerKeyId: 2 })}::jsonb,clock_timestamp()) RETURNING id`;
      await db`UPDATE pipeline_feedback SET evidence=evidence||${JSON.stringify({ reference_event_id: Number(event.id) })}::jsonb`;
    }
    if (change === "institution") await db`UPDATE pipeline_feedback SET institution_id=1000`;
    if (change === "category") await db`UPDATE pipeline_feedback SET canonical_fee_key='nsf'`;
    if (change === "amount") await db`UPDATE pipeline_feedback SET amount=26`;
    if (change === "source URL") await db`UPDATE pipeline_feedback SET source_url='https://other.example/fees'`;
    if (change === "source line") await db`UPDATE pipeline_feedback SET evidence=evidence||'{"source_line":"Other fee $25"}'::jsonb`;
    if (change === "fee name") await db`UPDATE pipeline_feedback SET evidence=evidence||'{"fee_name":"A different fee name"}'::jsonb`;
    if (change === "weight") await db`UPDATE pipeline_feedback SET weight=99`;
    expect(await trustedFeedbackCount()).toBe(0);
  });

  it("invalidates the learned category cache immediately after reference identity changes", async () => {
    await addFeedback();
    const before=await loadCategoryModel(asDb());expect(before?.categories).toContain("overdraft");
    await db`UPDATE answer_key_fees SET amount=26`;
    const after=await loadCategoryModel(asDb());expect(after?.categories).not.toContain("overdraft");
    expect(after?.categories).toContain("stop_payment");
  });

  it("keeps a valid original receipt across renewal and does not duplicate training weight", async () => {
    const { input, evidence } = await addFeedback();
    const before = await loadCategoryModel(asDb());
    expect(before).not.toBeNull();
    await approve();
    expect(await trustedFeedbackCount()).toBe(1);
    await db`INSERT INTO pipeline_feedback (about_stage,check_name,kind,signal,weight,institution_id,canonical_fee_key,amount,source_url,evidence,dedupe_key)
      VALUES ('extract','answer_key','answer_key','right',1,999,'overdraft',25,${input.key.documentUrl},${JSON.stringify(evidence)}::jsonb,'fixture-duplicate')`;
    resetCategoryModelCache();
    expect(await loadCategoryModel(asDb())).toEqual(before);
  });
});
