// @vitest-environment node
/** Real row-lock/CAS behavior in a random schema in an owned loopback database. */
import postgres from "postgres";
import { createHash, randomBytes } from "node:crypto";
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";

const state = vi.hoisted(() => ({
  db: null as postgres.Sql | null,
  events: [] as string[],
  cookies: [] as string[],
  hash: vi.fn(),
  verify: vi.fn(),
}));
vi.mock("@/lib/data-store/connection", () => ({
  sql: (strings: TemplateStringsArray, ...values: postgres.ParameterOrFragment<never>[]) => state.db!(strings, ...values),
  withTransaction: async (callback: (tx: postgres.TransactionSql) => Promise<unknown>) => {
    state.events.push("begin");
    const value = await state.db!.begin(callback);
    state.events.push("commit");
    return value;
  },
}));
vi.mock("@/lib/passwords", () => ({ hashPassword: state.hash, verifyPassword: state.verify }));
vi.mock("next/headers", () => ({
  cookies: async () => ({ set: (_name: string, value: string) => { state.cookies.push(value); state.events.push("cookie"); } }),
  headers: async () => new Headers(),
}));
vi.mock("next/server", () => ({ after: vi.fn() }));
vi.mock("@/lib/pro-institution-link", () => ({ linkVerifiedInstitutions: vi.fn(async () => undefined) }));
vi.mock("@/lib/api-hardening/login-rate-limit", () => ({
  reserveLoginAttempt: async () => "allowed", LOGIN_ATTEMPT_LIMITS: { windowMinutes: 15 }, LOGIN_IDENTIFIER_MAX_LENGTH: 320,
}));

const connection = process.env.E2E_DATABASE_URL;
const schema = `password_lifecycle_${randomBytes(8).toString("hex")}`;
const legacy = `test-salt:${createHash("sha256").update("test-salt:old password").digest("hex")}`;
const bcrypt = `$2b$10$${"a".repeat(53)}`;
const scrypt = `$scrypt$v1$N=131072,r=8,p=1$${"a".repeat(32)}$${"b".repeat(128)}`;
function deferred() {
  let resolve!: () => void;
  const promise = new Promise<void>((done) => { resolve = done; });
  return { promise, resolve };
}
function form(values: Record<string, string>) {
  const data = new FormData();
  for (const [key, value] of Object.entries(values)) data.set(key, value);
  return data;
}

describe.skipIf(!connection)("password login lifecycle in isolated PostgreSQL", () => {
  let admin: postgres.Sql;
  let db: postgres.Sql;
  beforeAll(async () => {
    if (!connection || !["localhost", "127.0.0.1", "[::1]"].includes(new URL(connection).hostname)) {
      throw new Error("Password lifecycle tests require a loopback E2E database");
    }
    admin = postgres(connection, { ssl: "require", prepare: false, onnotice: () => undefined });
    await admin`CREATE SCHEMA ${admin(schema)}`;
    // Copy columns/checks only: no public defaults, sequence or data is used.
    await admin`CREATE TABLE ${admin(schema)}.users (LIKE public.users INCLUDING CONSTRAINTS INCLUDING INDEXES)`;
    await admin`ALTER TABLE ${admin(schema)}.users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`;
    await admin`ALTER TABLE ${admin(schema)}.users ALTER COLUMN created_at SET DEFAULT now()`;
    await admin`CREATE TABLE ${admin(schema)}.sessions (LIKE public.sessions INCLUDING CONSTRAINTS INCLUDING INDEXES)`;
    await admin`ALTER TABLE ${admin(schema)}.sessions ALTER COLUMN created_at SET DEFAULT now()`;
    db = postgres(connection, { max: 8, ssl: "require", prepare: false, onnotice: () => undefined, connection: { search_path: schema } });
    state.db = db;
  });
  beforeEach(async () => {
    await db`ALTER TABLE sessions DROP CONSTRAINT IF EXISTS synthetic_insert_failure`;
    await db`TRUNCATE sessions, users RESTART IDENTITY`;
    await db`INSERT INTO users (username, email, password_hash, display_name, role, is_active)
      VALUES ('reader@example.test', 'reader@example.test', ${legacy}, 'Reader', 'viewer', true)`;
    state.events.length = 0;
    state.cookies.length = 0;
    state.hash.mockReset().mockImplementation(async (password: string) => `new-hash:${password}`);
    state.verify.mockReset().mockImplementation(async (_password: string, stored: string) => ({ valid: true, needsRehash: stored === legacy }));
    vi.spyOn(console, "error").mockImplementation(() => undefined);
  });
  afterAll(async () => {
    if (db) await db.end();
    if (admin) {
      await admin`DROP SCHEMA IF EXISTS ${admin(schema)} CASCADE`;
      await admin.end();
    }
    state.db = null;
  });

  const currentHash = async () => (await db`SELECT password_hash FROM users WHERE id = 1`)[0]?.password_hash;
  const sessionCount = async () => (await db`SELECT count(*)::int AS n FROM sessions`)[0].n;

  it("upgrades the selected legacy verifier and commits its session before emitting the cookie", async () => {
    const { login } = await import("./auth");
    expect(await login("reader@example.test", "old password")).toMatchObject({ id: 1 });
    expect(await currentHash()).toBe("new-hash:old password");
    expect(await sessionCount()).toBe(1);
    expect(state.events).toEqual(["begin", "commit", "cookie"]);
    expect(state.cookies).toHaveLength(1);
  });

  it.each([bcrypt, scrypt])("keeps a current verifier unchanged but still guards its session (%s)", async (stored) => {
    await db`UPDATE users SET password_hash = ${stored} WHERE id = 1`;
    const { login } = await import("./auth");
    expect(await login("reader@example.test", "old password")).toMatchObject({ id: 1 });
    expect(await currentHash()).toBe(stored);
    expect(state.hash).not.toHaveBeenCalled();
    expect(await sessionCount()).toBe(1);
    expect(state.events).toEqual(["begin", "commit", "cookie"]);
  });

  it.each([legacy, bcrypt, scrypt])("denies a stale verified credential when an actual reset wins first (%s)", async (stored) => {
    await db`UPDATE users SET password_hash = ${stored} WHERE id = 1`;
    const arrived = deferred();
    const resume = deferred();
    state.verify.mockImplementationOnce(async () => { arrived.resolve(); await resume.promise; return { valid: true, needsRehash: stored === legacy }; });
    const { login } = await import("./auth");
    const { createPasswordResetToken } = await import("./password-reset");
    const { resetPassword } = await import("@/app/(auth)/reset-password/actions");
    const pending = login("reader@example.test", "old password");
    await arrived.promise;
    try {
      const result = await resetPassword(form({ token: createPasswordResetToken(1, stored), password: "reset password", confirm: "reset password" }));
      expect(result).toEqual({ ok: true });
    } finally { resume.resolve(); }
    expect(await pending).toBeNull();
    expect(await currentHash()).toBe("new-hash:reset password");
    expect(await sessionCount()).toBe(0);
    expect(state.cookies).toHaveLength(0);
  });

  it.each([legacy, bcrypt, scrypt].flatMap((stored) => ["deactivate", "delete"].map((change) => ({ stored, change }))))(
    "denies a changed account after verification: $change ($stored)", async ({ stored, change }) => {
    await db`UPDATE users SET password_hash = ${stored} WHERE id = 1`;
    const arrived = deferred();
    const resume = deferred();
    state.verify.mockImplementationOnce(async () => { arrived.resolve(); await resume.promise; return { valid: true, needsRehash: stored === legacy }; });
    const { login } = await import("./auth");
    const pending = login("reader@example.test", "old password");
    await arrived.promise;
    try {
      if (change === "deactivate") await db`UPDATE users SET is_active = false WHERE id = 1`;
      else await db`DELETE FROM users WHERE id = 1`;
    } finally { resume.resolve(); }
    expect(await pending).toBeNull();
    expect(await sessionCount()).toBe(0);
    expect(state.cookies).toHaveLength(0);
  });

  it("lets only one concurrent legacy login replace the selected verifier", async () => {
    let arrivals = 0;
    const both = deferred();
    const resume = deferred();
    state.verify.mockImplementation(async () => { if (++arrivals === 2) both.resolve(); await resume.promise; return { valid: true, needsRehash: true }; });
    const { login } = await import("./auth");
    const pending = [login("reader@example.test", "old password"), login("reader@example.test", "old password")];
    await both.promise;
    resume.resolve();
    expect((await Promise.all(pending)).filter(Boolean)).toHaveLength(1);
    expect(await currentHash()).toBe("new-hash:old password");
    expect(await sessionCount()).toBe(1);
    expect(state.cookies).toHaveLength(1);
  });

  it("revokes a newly committed login session when a subsequent actual reset succeeds", async () => {
    const { login } = await import("./auth");
    const { createPasswordResetToken } = await import("./password-reset");
    const { resetPassword } = await import("@/app/(auth)/reset-password/actions");
    await login("reader@example.test", "old password");
    expect(await sessionCount()).toBe(1);
    const token = createPasswordResetToken(1, await currentHash());
    expect(await resetPassword(form({ token, password: "reset password", confirm: "reset password" }))).toEqual({ ok: true });
    expect(await currentHash()).toBe("new-hash:reset password");
    expect(await sessionCount()).toBe(0);
  });

  it("rolls the credential upgrade back if session insertion fails", async () => {
    await db`ALTER TABLE sessions ADD CONSTRAINT synthetic_insert_failure CHECK (false)`;
    const { login } = await import("./auth");
    await expect(login("reader@example.test", "old password")).rejects.toThrow();
    expect(await currentHash()).toBe(legacy);
    expect(await sessionCount()).toBe(0);
    expect(state.cookies).toHaveLength(0);
    expect(state.events).toEqual(["begin"]);
  });

  it("does no transaction or credential write for invalid passwords", async () => {
    state.verify.mockResolvedValueOnce({ valid: false, needsRehash: false });
    const { login } = await import("./auth");
    expect(await login("reader@example.test", "wrong password")).toBeNull();
    expect(await currentHash()).toBe(legacy);
    expect(state.hash).not.toHaveBeenCalled();
    expect(state.events).toHaveLength(0);
  });

  it("maps KDF admission failure through signup, reset and login without partial rows or sessions", async () => {
    const { createUserWithSession } = await import("./auth");
    const { createPasswordResetToken } = await import("./password-reset");
    const { resetPassword } = await import("@/app/(auth)/reset-password/actions");
    const { loginAction } = await import("@/app/(auth)/login/actions");
    state.hash.mockRejectedValue(new Error("synthetic KDF queue full"));
    expect(await createUserWithSession({ email: "new@example.test", password: "new password", displayName: "New" })).toMatchObject({ ok: false, code: "error" });
    expect(await resetPassword(form({ token: createPasswordResetToken(1, legacy), password: "reset password", confirm: "reset password" }))).toMatchObject({ ok: false, error: expect.stringContaining("unavailable") });
    expect(await loginAction(form({ username: "reader@example.test", password: "old password" }), "/account")).toMatchObject({ success: false, error: expect.stringContaining("temporarily unavailable") });
    expect(await db`SELECT count(*)::int AS n FROM users`).toEqual([{ n: 1 }]);
    expect(await currentHash()).toBe(legacy);
    expect(await sessionCount()).toBe(0);
    expect(state.events).toHaveLength(0);
    expect(state.cookies).toHaveLength(0);
  });

  it("uses the native full-input writer across real signup, reset and sign-in", async () => {
    const native = await vi.importActual<typeof import("./passwords")>("./passwords");
    state.hash.mockImplementation(native.hashPassword);
    state.verify.mockImplementation(native.verifyPassword);
    const { createUserWithSession, login } = await import("./auth");
    const { createPasswordResetToken } = await import("./password-reset");
    const { resetPassword } = await import("@/app/(auth)/reset-password/actions");
    const password = `${"\u00e9".repeat(40)}original suffix`;
    expect(await createUserWithSession({ email: "new@example.test", password, displayName: "New" })).toEqual({ ok: true, userId: 2 });
    const [{ password_hash: signupHash }] = await db`SELECT password_hash FROM users WHERE id = 2`;
    expect(signupHash).toMatch(/^\$scrypt\$v1\$/);
    expect(await native.verifyPassword(`${"\u00e9".repeat(40)}different suffix`, signupHash)).toMatchObject({ valid: false });
    expect(await login("new@example.test", password)).toMatchObject({ id: 2 });
    expect(await db`SELECT count(*)::int AS n FROM sessions WHERE user_id = 2`).toEqual([{ n: 2 }]);
    const newPassword = `${"a".repeat(72)}new reset suffix`;
    expect(await resetPassword(form({ token: createPasswordResetToken(2, signupHash), password: newPassword, confirm: newPassword }))).toEqual({ ok: true });
    expect(await db`SELECT count(*)::int AS n FROM sessions WHERE user_id = 2`).toEqual([{ n: 0 }]);
    expect(await login("new@example.test", password)).toBeNull();
    expect(await login("new@example.test", newPassword)).toMatchObject({ id: 2 });
  });

  it("upgrades a real legacy password beyond 72 UTF-8 bytes without accepting a different suffix", async () => {
    const native = await vi.importActual<typeof import("./passwords")>("./passwords");
    state.hash.mockImplementation(native.hashPassword);
    state.verify.mockImplementation(native.verifyPassword);
    const password = `${"\u00e9".repeat(40)}original suffix`;
    const selected = `test-salt:${createHash("sha256").update(`test-salt:${password}`).digest("hex")}`;
    await db`UPDATE users SET password_hash = ${selected} WHERE id = 1`;
    const { login } = await import("./auth");
    const { createPasswordResetToken, verifyPasswordResetToken } = await import("./password-reset");
    const oldToken = createPasswordResetToken(1, selected);
    expect(await login("reader@example.test", password)).toMatchObject({ id: 1 });
    const password_hash = await currentHash();
    expect(password_hash).toMatch(/^\$scrypt\$v1\$/);
    expect(verifyPasswordResetToken(oldToken, { id: 1, password_hash })).toBe(false);
    expect(await login("reader@example.test", `${"\u00e9".repeat(40)}different suffix`)).toBeNull();
    expect(await sessionCount()).toBe(1);
  });
});
