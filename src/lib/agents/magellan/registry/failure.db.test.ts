// @vitest-environment node
import { randomBytes } from "node:crypto";
import postgres from "postgres";
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { recordRegistryFailure } from "./failure";
import { REGISTRY_SOURCES, runRegistryStep } from "./index";
import { RegistryHttpError } from "@/lib/regulatory/http";
import type { RegistryDb } from "./partitions";
import { JSON_TEXT_PASSTHROUGH } from "@/lib/data-store/connection";

const connection = process.env.E2E_DATABASE_URL;
const schema = `registry_failure_${randomBytes(8).toString("hex")}`;
describe.skipIf(!connection)("registry failure receipts in isolated PostgreSQL", () => {
  let admin: postgres.Sql;
  let db: postgres.Sql<{ json: unknown }>;
  const asDb = () => db as unknown as RegistryDb;
  const input = (error: unknown, runId = 7) => ({ source: "bea-personal-income", partitionKey: "2024", runId, error });
  beforeAll(async () => {
    if (!connection || !["localhost","127.0.0.1","[::1]"].includes(new URL(connection).hostname)) throw new Error("Loopback test database required");
    admin = postgres(connection, { ssl: "require", prepare: false, onnotice: () => undefined });
    await admin`CREATE SCHEMA ${admin(schema)}`;
    await admin.unsafe(`CREATE TABLE "${schema}".registry_ingest_partitions (LIKE public.registry_ingest_partitions INCLUDING DEFAULTS INCLUDING CONSTRAINTS INCLUDING INDEXES)`);
    await admin.unsafe(`ALTER TABLE "${schema}".registry_ingest_partitions ALTER COLUMN id DROP DEFAULT`);
    await admin.unsafe(`ALTER TABLE "${schema}".registry_ingest_partitions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    db = postgres(connection, { ssl: "require", prepare: false, connection: { search_path: schema },
      types: { json: JSON_TEXT_PASSTHROUGH } });
  });
  beforeEach(async () => {
    vi.restoreAllMocks();
    await db`TRUNCATE registry_ingest_partitions RESTART IDENTITY`;
    await db`INSERT INTO registry_ingest_partitions(source,partition_key,status,attempts,agent_run_id,detail,next_attempt_after)
      VALUES('bea-personal-income','2024','scheduled',3,7,'{"claimed_parser_version":5}',now()+interval '6 hours')`;
  });
  afterAll(async () => {
    vi.restoreAllMocks();
    if (db) await db.end();
    if (admin) { await admin`DROP SCHEMA IF EXISTS ${admin(schema)} CASCADE`; await admin.end(); }
  });
  const row = async () => (await db`SELECT *,extract(epoch FROM next_attempt_after-now())/3600 AS hours FROM registry_ingest_partitions`)[0];

  it("records parser errors with attempt/version lineage and preserves claim backoff", async () => {
    expect(await recordRegistryFailure(asDb(),input(new Error("bad header")))).toMatchObject({ recorded: true, blocked: false });
    const r = await row();
    expect(r).toMatchObject({status:"failed",attempts:3,agent_run_id:"7",last_error:"bad header"});
    expect(r.detail).toMatchObject({claimed_parser_version:5,parser_version:5,failure_kind:"transport_or_parser"});
    expect(Number(r.hours)).toBeGreaterThan(5.9);
  });

  it.each([401,403])("records a publisher HTTP %i as unavailable with weekly backoff and redacted credentials", async status => {
    const error = new RegistryHttpError("HTTP refusal https://apps.bea.gov?UserID=secret&year=2024","https://apps.bea.gov?UserID=secret&year=2024",status);
    expect(await recordRegistryFailure(asDb(),input(error))).toMatchObject({ recorded:true,blocked:true });
    const r = await row();
    expect(r.status).toBe("empty");
    expect(r.detail.missing_source).toMatchObject({host:"apps.bea.gov",status});
    expect(JSON.stringify(r)).not.toContain("secret");
    expect(Number(r.hours)).toBeGreaterThan(167.9);
  });

  it("preserves newer ownership and makes repeated completion idempotent", async () => {
    const error = new Error("old worker");
    expect((await recordRegistryFailure(asDb(),input(error,6))).recorded).toBe(false);
    expect((await row()).status).toBe("scheduled");
    await recordRegistryFailure(asDb(),input(error));
    const first = await row();
    expect((await recordRegistryFailure(asDb(),input(new Error("late repeat")))).recorded).toBe(false);
    expect((await row()).updated_at).toEqual(first.updated_at);
    await db`UPDATE registry_ingest_partitions SET status='succeeded',last_error=NULL`;
    expect((await recordRegistryFailure(asDb(),input(error))).recorded).toBe(false);
    expect((await row()).status).toBe("succeeded");
  });

  it.each([400,404,429,503])("records HTTP %i with bounded status-specific backoff", async status => {
    await recordRegistryFailure(asDb(),input(new RegistryHttpError("HTTP error","https://example.gov/data",status)));
    const r = await row();
    expect(r.status).toBe("failed");
    expect(Number(r.hours)).toBeGreaterThan([400,404].includes(status) ? 23.9 : 5.9);
  });

  it("the real dispatcher records an exception and preserves its original cause", async () => {
    const definition = REGISTRY_SOURCES.find(s=>s.source==="bea-personal-income")!;
    const error = new Error("BEA parser failed");
    vi.spyOn(definition,"run").mockRejectedValue(error);
    await expect(runRegistryStep({stepKey:definition.stepKey,partitionKey:"2024",runId:7,dryRun:false,db:asDb()})).rejects.toBe(error);
    expect((await row()).last_error).toBe(error.message);
  });

  it("dry-run exceptions persist no receipt, even when the publisher refuses", async () => {
    const definition = REGISTRY_SOURCES.find(s=>s.source==="bea-personal-income")!;
    const error = new RegistryHttpError("Refused","https://example.gov",403);
    vi.spyOn(definition,"run").mockRejectedValue(error);
    await expect(runRegistryStep({stepKey:definition.stepKey,partitionKey:"2024",runId:7,dryRun:true,db:asDb()})).rejects.toBe(error);
    expect((await row()).status).toBe("scheduled");
  });

  it("a receipt-write failure does not replace the worker's error", async () => {
    const definition = REGISTRY_SOURCES.find(s=>s.source==="bea-personal-income")!;
    const error = new Error("original parser error");
    vi.spyOn(definition,"run").mockRejectedValue(error);
    vi.spyOn(console,"error").mockImplementation(()=>{});
    const failedDb = vi.fn().mockRejectedValue(new Error("database offline")) as unknown as RegistryDb;
    await expect(runRegistryStep({stepKey:definition.stepKey,partitionKey:"2024",runId:7,dryRun:false,db:failedDb})).rejects.toBe(error);
  });
});
